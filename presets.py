def apply_preset_to_props(props: Any, preset_id: str) -> None:
    preset = WORLD_PRESETS.get(preset_id, WORLD_PRESETS["CLASSIC_BRYCE"])
    was_updating = getattr(props, "is_applying_preset", False)
    props.is_applying_preset = True
    try:
        if getattr(props, "world_preset", None) != preset_id:
            props.world_preset = preset_id
        for field in RECIPE_FIELDS:
            if field in preset and hasattr(props, field):
                setattr(props, field, preset[field])
    finally:
        props.is_applying_preset = was_updating


def props_to_recipe_dict(props: Any) -> Dict[str, Any]:
    params: Dict[str, Any] = {}
    for field in RECIPE_FIELDS:
        if hasattr(props, field):
            val = getattr(props, field)
            if hasattr(val, "__len__") and not isinstance(val, str):
                val = [ round(float(x), 4) for x in val ]
            elif isinstance(val, float):
                val = round(val, 4)
            params[field] = val
    return {
        "schema": "late_90s_graphics_lab.recipe.v3.3",
        "version": "3.10.0",
        "world_preset": getattr(props, "world_preset", "CLASSIC_BRYCE"),
        "parameters": params,
    }


def apply_recipe_dict_to_props(props: Any, data: Dict[str, Any]) -> None:
    params = data.get("parameters", data)
    was_updating = getattr(props, "is_applying_preset", False)
    props.is_applying_preset = True
    try:
        for field in RECIPE_FIELDS:
            if field in params and hasattr(props, field):
                val = params[field]
                if isinstance(val, list):
                    val = tuple(val)
                try:
                    setattr(props, field, val)
                except Exception:
                    pass
    finally:
        props.is_applying_preset = was_updating


def save_recipe_json(props: Any, filepath: str) -> Dict[str, Any]:
    data = props_to_recipe_dict(props)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return data


def load_recipe_json(props: Any, filepath: str) -> Dict[str, Any]:
    with open(filepath, "r", encoding="utf-8") as f:
        data = json.load(f)
    apply_recipe_dict_to_props(props, data)
    return data
